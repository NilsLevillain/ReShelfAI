const isLeaf = (n) => n && typeof n === 'object' && '$value' in n;
const lookup = (path) => path.split('.').reduce((o, k) => o?.[k], src);

function resolve(v) {
  if (typeof v === 'string') {
    return v.replace(/\{([^}]+)\}/g, (_, p) => {
      const n = lookup(p);
      if (!isLeaf(n)) throw new Error(`Unresolved token reference: ${p}`);
      return String(resolve(n.$value));
    });
  }
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolve(x)]));
  return v;
}

// Walk a group and return [pathArray, resolvedValue] pairs.
function flatten(node, path = []) {
  const out = [];
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (isLeaf(v)) out.push([[...path, k], resolve(v.$value)]);
    else if (v && typeof v === 'object') out.push(...flatten(v, [...path, k]));
  }
  return out;
}

// Same shape as the source, with $value unwrapped and references resolved.
function plain(node) {
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    out[k] = isLeaf(v) ? resolve(v.$value) : plain(v);
  }
  return out;
}

const rem = (px) => `${px / 16}rem`;
const px = (n) => `${n}px`;
// Numbers become rem or px, strings such as clamp(...) or 1.06em pass through.
const remOrRaw = (v) => (v !== '' && !Number.isNaN(Number(v)) ? rem(Number(v)) : v);
const pxOrRaw = (v) => (!Number.isNaN(Number(v)) ? px(Number(v)) : v);
const name = (path) => `--rs-${path.join('-')}`;

// CSS value formatting per top level group.
function cssValue(path, value) {
  const [g, sub] = path;
  if (g === 'type' && (sub === 'size' || sub === 'line')) return rem(value);
  if (g === 'space' || g === 'size') return rem(value);
  if (g === 'radius') return px(value);
  if (g === 'motion' && sub === 'duration') return `${value}ms`;
  if (g === 'layout' || g === 'breakpoint') return pxOrRaw(value);
  return String(value);
}

